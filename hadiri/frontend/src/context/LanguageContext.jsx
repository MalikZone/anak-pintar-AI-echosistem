export function LanguageProvider({ children }) {
  const [language, setLanguageState] = useState(() => {
    return localStorage.getItem('hadirin_lang') || 'id';
  });

  useEffect(() => {
    localStorage.setItem('hadirin_lang', language);
  }, [language]);

  const setLanguage = (lang) => {
    if (lang === 'id' || lang === 'en') {
      setLanguageState(lang);
    }
  };

  const toggleLanguage = () => {
    setLanguageState((prev) => (prev === 'id' ? 'en' : 'id'));
  };

  const t = (key, fallbackOrParams = '', params = {}) => {
    let fallback = '';
    let replacers = params;
    if (typeof fallbackOrParams === 'object' && fallbackOrParams !== null) {
      replacers = fallbackOrParams;
      fallback = '';
    } else if (typeof fallbackOrParams === 'string') {
      fallback = fallbackOrParams;
    }

    let text = translations[language]?.[key] || translations.id[key] || fallback || key;
    if (replacers && typeof replacers === 'object') {
      Object.entries(replacers).forEach(([paramKey, val]) => {
        text = text.replace(new RegExp(`\\{${paramKey}\\}`, 'g'), String(val));
      });
    }
    return text;
  };

  return (
    <LanguageContext.Provider
      value={{
        language,
        isId: language === 'id',
        isEn: language === 'en',
        setLanguage,
        toggleLanguage,
        t,
        getDayName: (input) => getDayNameHelper(input, language),
        getShortDayName: (input) => getShortDayNameHelper(input, language),
        formatDate: (date, withDayName = true) => formatDateLocale(date, language, withDayName),
        formatShortDate: (date) => formatShortDateLocale(date, language),
      }}
    >
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error('useLanguage must be used within a LanguageProvider');
  }
  return context;
}
